import math

# Número de ejemplo
numero = 16

# Raíz cuadrada
print("Raíz cuadrada:")
print(math.sqrt(numero))

# Potencia
print("\nPotencia (2^3):")
print(math.pow(2, 3))

# Valor de pi
print("\nValor de pi:")
print(math.pi)

# Redondeo hacia arriba
print("\nRedondeo hacia arriba de 4.3:")
print(math.ceil(4.3))